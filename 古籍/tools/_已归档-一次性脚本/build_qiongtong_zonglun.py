def original_lines(path):
    out, ann = [], False
    for l in open(path, encoding='utf-8').read().split('\n'):
        s = l.rstrip()
        if s.startswith('## '):
            ann = True
            continue
        if ann or not s.strip() or s.startswith('#') or s.startswith('>'):
            continue
        out.append(s)
    return out

def split_sections(lines, markers):
    idxs = []
    for m in markers:
        for i, l in enumerate(lines):
            if l.startswith(m):
                idxs.append(i)
                break
        else:
            raise SystemExit(f'分节标记未找到: {m}')
    assert idxs == sorted(idxs), markers
    segs = []
    for k, i in enumerate(idxs):
        j = idxs[k + 1] if k + 1 < len(idxs) else len(lines)
        segs.append(lines[i:j])
    return segs

