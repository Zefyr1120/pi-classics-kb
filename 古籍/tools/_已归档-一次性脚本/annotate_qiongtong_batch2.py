D = os.path.join(BOOK, '05-丁火')

def body_lines(path):
    out = []
    for l in open(path, encoding='utf-8').read().split('\n'):
        s = l.rstrip()
        if s.startswith('#') or s.startswith('>') or s.startswith('## '):
            continue
        out.append(s)
    return out

